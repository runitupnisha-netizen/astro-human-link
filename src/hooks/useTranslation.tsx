interface TranslationContextValue {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  languages: typeof LANGUAGE_LABELS;
}

const TranslationContext = createContext<TranslationContextValue>({
  language: "en",
  setLanguage: () => {},
  t: (key) => key,
  languages: LANGUAGE_LABELS,
});

export const TranslationProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem("stellara_language");
    return (saved as Language) || "en";
  });

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("stellara_language", lang);
  }, []);

  const t = useCallback((key: string) => {
    return translations[language]?.[key] || translations.en[key] || key;
  }, [language]);

  return (
    <TranslationContext.Provider value={{ language, setLanguage, t, languages: LANGUAGE_LABELS }}>
      {children}
    </TranslationContext.Provider>
  );
};

export const useTranslation = () => useContext(TranslationContext);
